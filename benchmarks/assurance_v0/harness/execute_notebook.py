"""Execute trusted generated notebook cells without adding a notebook dependency."""

from __future__ import annotations

import argparse
import contextlib
import io
import json
import os
import traceback
from pathlib import Path
from typing import Any


def _source_text(cell: dict[str, Any]) -> str:
    source = cell.get("source", "")
    return "".join(source) if isinstance(source, list) else str(source)


def execute_notebook(notebook_path: Path, output_path: Path) -> dict[str, Any]:
    """Execute code cells sequentially and write an executed notebook.

    This is limited to trusted notebooks generated by this benchmark. It is not a sandbox
    and must not be used to execute untrusted submissions.
    """
    notebook_path = notebook_path.resolve()
    output_path = output_path.resolve()
    notebook = json.loads(notebook_path.read_text(encoding="utf-8"))
    namespace: dict[str, Any] = {"__name__": "__main__"}
    original_cwd = Path.cwd()
    execution_count = 0
    succeeded = False

    try:
        os.chdir(notebook_path.parent)
        for cell_index, cell in enumerate(notebook["cells"]):
            if cell.get("cell_type") != "code":
                continue
            execution_count += 1
            cell["execution_count"] = execution_count
            stdout = io.StringIO()
            stderr = io.StringIO()
            try:
                with contextlib.redirect_stdout(stdout), contextlib.redirect_stderr(stderr):
                    code = compile(
                        _source_text(cell),
                        f"{notebook_path.name}#cell-{cell_index}",
                        "exec",
                    )
                    exec(code, namespace)
            except Exception as exc:
                cell["outputs"] = [
                    {
                        "ename": type(exc).__name__,
                        "evalue": str(exc),
                        "output_type": "error",
                        "traceback": traceback.format_exc().splitlines(),
                    }
                ]
                raise
            else:
                outputs: list[dict[str, Any]] = []
                if stdout.getvalue():
                    outputs.append(
                        {
                            "name": "stdout",
                            "output_type": "stream",
                            "text": stdout.getvalue(),
                        }
                    )
                if stderr.getvalue():
                    outputs.append(
                        {
                            "name": "stderr",
                            "output_type": "stream",
                            "text": stderr.getvalue(),
                        }
                    )
                cell["outputs"] = outputs
        succeeded = True
    finally:
        os.chdir(original_cwd)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(
            json.dumps(notebook, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
            newline="\n",
        )

    return {
        "input": str(notebook_path),
        "output": str(output_path),
        "executed_code_cells": execution_count,
        "succeeded": succeeded,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("notebook", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    result = execute_notebook(args.notebook, args.output)
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
